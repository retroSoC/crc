#ifndef CRC_REGS_H
#define CRC_REGS_H

#include <stdint.h>

#define CRC_CTRL_OFFSET               UINT32_C(0x000)
#define CRC_STATUS_OFFSET             UINT32_C(0x004)
#define CRC_CONFIG_OFFSET             UINT32_C(0x008)
#define CRC_POLYNOMIAL_OFFSET         UINT32_C(0x00C)
#define CRC_INIT_OFFSET               UINT32_C(0x010)
#define CRC_XOR_OUT_OFFSET            UINT32_C(0x014)
#define CRC_DATA_OFFSET               UINT32_C(0x018)
#define CRC_RESULT_OFFSET             UINT32_C(0x01C)
#define CRC_RAW_STATE_OFFSET          UINT32_C(0x020)
#define CRC_BYTE_COUNT_OFFSET         UINT32_C(0x024)
#define CRC_ERROR_STATUS_OFFSET       UINT32_C(0x028)
#define CRC_CONFIG_LOCK_OFFSET        UINT32_C(0x02C)
#define CRC_IP_ID_OFFSET              UINT32_C(0x0F4)
#define CRC_IP_VERSION_OFFSET         UINT32_C(0x0F8)
#define CRC_CAPABILITY_OFFSET         UINT32_C(0x0FC)

#define CRC_CTRL_START_MASK           UINT32_C(0x00000001)
#define CRC_CTRL_FINISH_MASK          UINT32_C(0x00000002)
#define CRC_CTRL_ABORT_MASK           UINT32_C(0x00000004)
#define CRC_CTRL_VALID_MASK           UINT32_C(0x00000007)

#define CRC_STATUS_ACTIVE_MASK        UINT32_C(0x00000001)
#define CRC_STATUS_RESULT_VALID_MASK  UINT32_C(0x00000002)
#define CRC_STATUS_CONFIG_LOCKED_MASK UINT32_C(0x00000004)
#define CRC_STATUS_ERROR_MASK         UINT32_C(0x00000008)

#define CRC_CONFIG_WIDTH_MASK         UINT32_C(0x00000003)
#define CRC_CONFIG_REFLECT_IN_MASK    UINT32_C(0x00000004)
#define CRC_CONFIG_REFLECT_OUT_MASK   UINT32_C(0x00000008)
#define CRC_CONFIG_BYTE_SWAP_MASK     UINT32_C(0x00000010)
#define CRC_CONFIG_VALID_MASK         UINT32_C(0x0000001F)

#define CRC_ERROR_ACCESS_MASK         UINT32_C(0x00000001)
#define CRC_ERROR_STATE_MASK          UINT32_C(0x00000002)
#define CRC_ERROR_CONFIG_MASK         UINT32_C(0x00000004)
#define CRC_ERROR_COUNT_OVERFLOW_MASK UINT32_C(0x00000008)
#define CRC_ERROR_VALID_MASK          UINT32_C(0x0000000F)
#define CRC_ERROR_ALL_MASK            CRC_ERROR_VALID_MASK

#define CRC_CONFIG_LOCK_MASK          UINT32_C(0x00000001)

#define CRC_IP_ID_VALUE               UINT32_C(0x43524332)
#define CRC_IP_VERSION_VALUE          UINT32_C(0x00020000)
#define CRC_CAPABILITY_FEATURES       UINT32_C(0xFF)
#define CRC_CAPABILITY_VALUE          UINT32_C(0x020000FF)
#define CRC_CAPABILITY_ABI_MASK       UINT32_C(0xFF000000)
#define CRC_CAPABILITY_ABI_SHIFT      24U
#define CRC_ABI_VERSION               UINT32_C(0x02)

#endif
